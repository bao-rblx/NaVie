"""Generate browser translations from the shared Flutter ARB source of truth."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    """Write dependency-free JavaScript translations for the standalone web app."""
    locales = {}
    for locale in ("vi", "en"):
        source = ROOT / "app" / "lib" / "l10n" / f"app_{locale}.arb"
        locales[locale] = {
            key: value
            for key, value in json.loads(source.read_text(encoding="utf-8")).items()
            if not key.startswith("@")
        }
    target = ROOT / "app" / "web_app" / "locales.mjs"
    target.write_text(
        "// Generated by scripts/build_web_locales.py. Edit app/lib/l10n/*.arb.\n"
        + "export const locales = "
        + json.dumps(locales, ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
